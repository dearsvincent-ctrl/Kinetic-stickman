export const upgradeCost = (definition, level) =>
  Math.ceil(definition.costBase + level * definition.costGrowth);
// Bounded diminishing growth; rank 0 is exactly the established gameplay baseline.
export const statMultiplier = (definition, level) =>
  1 +
  definition.gain *
    (1 - Math.exp(-Math.max(0, Math.min(definition.maxLevel, level)) / 5));
